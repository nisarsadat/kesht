export type MessageKey = keyof typeof fa;

const catalogs: Record<Language, Record<MessageKey, string>> = { fa, en };

export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = catalogs[language][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function ruleMessage(language: Language, code: RuleCode): string {
  return catalogs[language][code];
}
